#!/usr/bin/env python3
"""Generate the bundled TTS 2.0 catalog from a saved official tone-list HTML page.

Download https://docs.volcengine.com/docs/doubao-voice/tone-list-3?lang=zh,
then run this script with --html FILE. No account credentials or API calls.
"""
import argparse
import json
import re
from datetime import date
from html.parser import HTMLParser
from pathlib import Path

SOURCE = "https://docs.volcengine.com/docs/doubao-voice/tone-list-3?lang=zh"


def clean(text):
    return re.sub(r"\s+", " ", text.replace("\u200b", "").replace("\ufeff", "")).strip()


class Tables(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tables = []
        self.heading = ""
        self.heading_parts = None
        self.table = None
        self.row = None
        self.cell = None

    def handle_starttag(self, tag, attrs):
        if tag == "h2":
            self.heading_parts = []
        if tag == "table":
            self.table = []
        elif tag == "tr" and self.table is not None:
            self.row = []
        elif tag in ("td", "th") and self.row is not None:
            props = dict(attrs)
            if int(props.get("colspan", 1)) != 1 or int(props.get("rowspan", 1)) != 1:
                # 2.0 tables currently contain complete rows. Fail rather than
                # silently assigning a speaker to the wrong column after a redesign.
                if "语音合成模型2.0" in self.heading:
                    raise ValueError("Unexpected merged cell in TTS 2.0 table")
            self.cell = []
        elif tag in ("br", "p") and self.cell is not None:
            self.cell.append(" ")

    def handle_data(self, data):
        if self.heading_parts is not None:
            self.heading_parts.append(data)
        if self.cell is not None:
            self.cell.append(data)

    def handle_endtag(self, tag):
        if tag == "h2" and self.heading_parts is not None:
            self.heading = clean("".join(self.heading_parts))
            self.heading_parts = None
        elif tag in ("td", "th") and self.cell is not None:
            self.row.append(clean("".join(self.cell)))
            self.cell = None
        elif tag == "tr" and self.row is not None:
            self.table.append(self.row)
            self.row = None
        elif tag == "table" and self.table is not None:
            self.tables.append((self.heading, self.table))
            self.table = None


def catalog(html):
    parser = Tables()
    parser.feed(html)
    voices = {}
    count = 0
    for heading, rows in parser.tables:
        if "语音合成模型2.0" not in heading:
            continue
        count += 1
        headers = rows[0]
        fields = [headers.index(k) for k in ("voice_type", "音色名称", "场景", "语种/方言")]
        for row in rows[1:]:
            if len(row) != len(headers):
                raise ValueError("Unexpected row width in " + heading)
            speaker, name, scene, language = [row[i] for i in fields]
            if not re.fullmatch(r"[A-Za-z0-9_-]+", speaker) or "_uranus_" not in speaker:
                raise ValueError("Unexpected TTS 2.0 speaker: " + speaker)
            if not name or not language:
                raise ValueError("Missing name/language for " + speaker)
            item = dict(id=speaker, name=name, scene=scene, language=language)
            if speaker in voices and voices[speaker] != item:
                raise ValueError("Conflicting duplicate speaker: " + speaker)
            voices[speaker] = item
    if count != 2 or len(voices) < 100:
        raise ValueError("Expected the two official TTS 2.0 tables")
    return list(voices.values())


def render(voices, snapshot_date):
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = [
        "import Foundation", "",
        "// Generated by scripts/update_doubao_voice_catalog.py; do not edit rows by hand.",
        "// Source: " + SOURCE,
        f"// Snapshot: {snapshot_date}. Catalog membership does not prove account authorization.",
        "enum DoubaoVoiceCatalog {",
        "    struct Voice: Identifiable, Sendable {",
        "        let id: String",
        "        let name: String",
        "        let scene: String",
        "        let language: String",
        '        var isChinese: Bool { language.contains("中文") }',
        "    }", "",
        "    static let voices: [Voice] = [",
    ]
    for voice in voices:
        args = ", ".join(key + ": " + quote(voice[key]) for key in ("id", "name", "scene", "language"))
        lines.append("        Voice(" + args + "),")
    lines += ["    ]", "", "    static let byID = Dictionary(uniqueKeysWithValues: voices.map { ($0.id, $0) })", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument("--html", required=True, type=Path)
    args.add_argument("--snapshot-date", type=date.fromisoformat, default=date.today())
    args.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "src/ios/Providers/Voice/DoubaoVoiceCatalog.swift")
    options = args.parse_args()
    voices = catalog(options.html.read_text())
    options.output.write_text(render(voices, options.snapshot_date.isoformat()))
    chinese = sum("中文" in voice["language"] for voice in voices)
    print(f"Generated {len(voices)} TTS 2.0 voices: {chinese} Chinese, {len(voices) - chinese} international")
