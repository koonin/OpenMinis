/// Local adaptations of the console's built-in personas, reviewed 2026-10-29.
/// Names identify the source presets; prose is written for the shared SOUL editor.
/// Voice-only entries without a dedicated persona are intentionally omitted.
enum SoulRoleCategory: String, CaseIterable, Identifiable {
    case friends = "Everyday Friends"
    case companions = "Gentle Companions"
    case dialects = "Regional Characters"
    case helpers = "Advisors and Teachers"
    case characters = "Character Play"
    case playful = "Playful Characters"
    case storytellers = "Storytellers"
    case elders = "Caring Elders"
    case general = "General Templates"

    var id: String { rawValue }

    var searchTerms: String {
        switch self {
        case .friends: return "朋友 日常 开朗"
        case .companions: return "陪伴 温柔 治愈"
        case .dialects: return "方言 地域 家乡"
        case .helpers: return "知性 学习 老师 助手"
        case .characters: return "个性 角色 扮演"
        case .playful: return "童趣 孩童 伙伴"
        case .storytellers: return "故事 朗读 叙述"
        case .elders: return "长辈 家人 关怀"
        case .general: return "通用 模板"
        }
    }
}

struct SoulRoleTemplate: Identifiable {
    let id: String
    let name: String
    let summary: String
    let style: String
    let body: String
    var reference: String? = nil
    var category: SoulRoleCategory = .general
    var language: String = "跟随对话"
    var aliases: [String] = []
    var isConsoleRole = false

    static let all = [taiwanFriend] + mandarinRoles + englishRoles + japaneseRoles
        + cantoneseRoles + internationalRoles + generalRoles

    static var languages: [String] {
        let preferred = ["普通话", "粤语", "英语", "日语", "跟随对话"]
        let available = Set(all.map(\.language))
        return preferred.filter { available.contains($0) }
            + available.subtracting(preferred).sorted { $0.localizedStandardCompare($1) == .orderedAscending }
    }

    static func matching(style: String, body: String) -> Self? {
        all.first { $0.style == style && $0.body == body }
    }

    static func filtered(query: String, category: SoulRoleCategory? = nil, language: String? = nil) -> [Self] {
        let terms = query.split(whereSeparator: \.isWhitespace).map(String.init)
        return all.filter { role in
            guard category == nil || role.category == category,
                  language == nil || role.language == language else { return false }
            let searchable = ([role.name, role.summary, role.style, role.language,
                               role.category.rawValue, role.category.searchTerms] + role.aliases).joined(separator: " ")
            return terms.allSatisfy {
                searchable.range(of: $0, options: [.caseInsensitive, .diacriticInsensitive, .widthInsensitive]) != nil
            }
        }
    }

    private static func console(_ id: String, _ name: String, _ category: SoulRoleCategory,
                                _ language: String, _ summary: String, _ style: String,
                                _ interaction: String, aliases: [String] = []) -> Self {
        let languageGuidance = language == "普通话" ? "" : "默认用\(language)交流；用户指定其他语言时按用户要求切换。"
        return Self(id: id, name: name, summary: summary, style: style,
                    body: """
                    ## 角色气质
                    \(summary)。以这种角色气质与用户交流，保留现有的助手名称。

                    ## 互动方式
                    \(interaction)

                    ## 表达方式
                    \(style)\(languageGuidance)
                    按对话情境自然表达，不反复套用口头禅。角色扮演不代表真实经历或现实关系；处理实际问题时仍应清楚、诚实，尊重用户的选择。
                    """,
                    category: category, language: language, aliases: aliases, isConsoleRole: true)
    }

